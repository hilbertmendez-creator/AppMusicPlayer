"""Ports: the interfaces the application layer depends on."""

from __future__ import annotations

from pathlib import Path
from typing import Protocol

from app.domain.models import (
    DownloadedAudio,
    DownloadJob,
    Lyrics,
    Playlist,
    SearchResult,
    Song,
    TrackHint,
)


class MusicSource(Protocol):
    def search(self, query: str, limit: int) -> list[SearchResult]: ...

    def download_audio(self, source_id: str, dest_dir: Path) -> DownloadedAudio: ...


class LyricsProvider(Protocol):
    def get(self, title: str, artist: str, duration_seconds: int | None) -> Lyrics | None: ...


class LyricsSearch(Protocol):
    def find_by_fragment(self, fragment: str, limit: int) -> list[TrackHint]: ...


class AudioStorage(Protocol):
    def store(self, src: Path, song_id: str) -> str: ...

    def path_of(self, filename: str) -> Path: ...

    def delete(self, filename: str) -> None: ...


class LibraryRepository(Protocol):
    # identity
    def library_id(self) -> str: ...
    # songs
    def add_song(self, song: Song) -> None: ...
    def get_song(self, song_id: str) -> Song | None: ...
    def get_song_by_source_id(self, source_id: str) -> Song | None: ...
    def list_songs(self) -> list[Song]: ...
    def update_song(self, song: Song) -> None: ...
    def delete_song(self, song_id: str) -> None: ...
    def source_ids_in_library(self, source_ids: list[str]) -> set[str]: ...
    # playlists
    def add_playlist(self, playlist: Playlist) -> None: ...
    def get_playlist(self, playlist_id: str) -> Playlist | None: ...
    def list_playlists(self) -> list[Playlist]: ...
    def update_playlist(self, playlist: Playlist) -> None: ...
    def delete_playlist(self, playlist_id: str) -> None: ...
    # jobs
    def add_job(self, job: DownloadJob) -> None: ...
    def get_job(self, job_id: str) -> DownloadJob | None: ...
    def get_active_job_for_source(self, source_id: str) -> DownloadJob | None: ...
    def list_jobs(self) -> list[DownloadJob]: ...
    def update_job(self, job: DownloadJob) -> None: ...
